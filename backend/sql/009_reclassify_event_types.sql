DECLARE bad_events INT; bad_news INT;
BEGIN
  SELECT count(*) INTO bad_events FROM events
    WHERE event_type NOT IN ('military','passage','energy','freight','finance','diplomacy','civil','other');
  SELECT count(*) INTO bad_news FROM news
    WHERE event_type NOT IN ('military','passage','energy','freight','finance','diplomacy','civil','other');
